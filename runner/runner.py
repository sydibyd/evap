"""EVAP SIL runner.

Polls the EVAP API for queued validation runs and executes each approved script revision
against the exact Git commit of the System Under Test, inside a disposable sandbox container:

  * non-root user, no network, CPU/memory/PID limits, all capabilities dropped,
    no-new-privileges, no host mounts, no Docker socket, no credentials, hard timeout.

The runner itself never imports or executes user test code.
"""
import hashlib
import io
import json
import logging
import os
import subprocess
import tarfile
import time
import urllib.error
import urllib.request

import docker
from docker.errors import DockerException

API = os.environ.get("EVAP_API_URL", "http://backend:8000").rstrip("/")
TOKEN = os.environ["EVAP_RUNNER_TOKEN"]
POLL_S = float(os.environ.get("RUNNER_POLL_SECONDS", "2"))
CACHE = os.environ.get("RUNNER_CACHE_DIR", "/var/cache/evap/repos")
SSH_KEY = os.environ.get("RUNNER_GIT_SSH_KEY", "/run/secrets/git_deploy_key")
KNOWN_HOSTS = os.environ.get("RUNNER_KNOWN_HOSTS", "/app/known_hosts")
IMAGES = {"python3.11": os.environ.get("SANDBOX_IMAGE", "evap-v2-sandbox:latest")}
MEM = os.environ.get("SANDBOX_MEMORY", "256m")
CPUS = float(os.environ.get("SANDBOX_CPUS", "1.0"))
PIDS = int(os.environ.get("SANDBOX_PIDS", "128"))
SANDBOX_UID = 10001

CONFTEST = '''# Generated by EVAP: makes the System Under Test importable.
import sys
sys.path.insert(0, "/work/sut")
'''

logging.basicConfig(level=logging.INFO, format="%(asctime)s runner %(levelname)s %(message)s")
log = logging.getLogger("runner")


# --- EVAP API -------------------------------------------------------------------
def api(method: str, path: str, body: dict | None = None) -> dict:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(f"{API}{path}", data=data, method=method, headers={
        "Authorization": f"Bearer {TOKEN}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read() or b"{}")


# --- Git --------------------------------------------------------------------------
def git_env() -> dict:
    env = {"PATH": os.environ["PATH"], "HOME": os.environ.get("HOME", "/tmp"),
           "GIT_TERMINAL_PROMPT": "0"}
    if os.path.isfile(SSH_KEY) and os.path.getsize(SSH_KEY) > 0:
        env["GIT_SSH_COMMAND"] = (f"ssh -i {SSH_KEY} -o IdentitiesOnly=yes -o BatchMode=yes "
                                  f"-o StrictHostKeyChecking=yes -o UserKnownHostsFile={KNOWN_HOSTS}")
    return env


def git(*args: str, cwd: str | None = None, binary: bool = False):
    # Arguments are passed as a list (never through a shell). "--" separates refs where relevant.
    out = subprocess.run(["git", *args], cwd=cwd, env=git_env(), capture_output=True, timeout=300)
    if out.returncode != 0:
        raise RuntimeError(f"git {args[0]} failed: {out.stderr.decode(errors='replace').strip()[:2000]}")
    return out.stdout if binary else out.stdout.decode().strip()


def mirror(repo_url: str) -> str:
    path = os.path.join(CACHE, hashlib.sha256(repo_url.encode()).hexdigest()[:24] + ".git")
    if not os.path.isdir(path):
        git("clone", "--mirror", "--quiet", "--", repo_url, path)
    else:
        git("fetch", "--prune", "--quiet", "origin", cwd=path)
    return path


def resolve_commit(path: str, branch: str, sha: str | None) -> str:
    if sha:
        git("cat-file", "-e", f"{sha}^{{commit}}", cwd=path)
        return git("rev-parse", f"{sha}^{{commit}}", cwd=path)
    return git("rev-parse", "--verify", f"refs/heads/{branch}^{{commit}}", cwd=path)


# --- Workspace ---------------------------------------------------------------------
def _add(tar: tarfile.TarFile, name: str, data: bytes, mode: int = 0o644) -> None:
    ti = tarfile.TarInfo(name)
    ti.size, ti.mode, ti.uid, ti.gid, ti.mtime = len(data), mode, SANDBOX_UID, SANDBOX_UID, int(time.time())
    tar.addfile(ti, io.BytesIO(data))


def build_workspace(sut_tar: bytes, test_name: str, source: str) -> bytes:
    """Repack `git archive` output under sut/ and add the test script; owned by the sandbox user."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as out, tarfile.open(fileobj=io.BytesIO(sut_tar)) as src:
        for m in src.getmembers():
            if not (m.isfile() or m.isdir()):
                continue  # drop symlinks/devices from the SUT archive
            if m.name.startswith("/") or ".." in m.name.split("/"):
                continue
            m.name = "sut/" + m.name
            m.uid = m.gid = SANDBOX_UID
            m.uname = m.gname = ""
            m.mode = 0o755 if m.isdir() else 0o644
            out.addfile(m, src.extractfile(m) if m.isfile() else None)
        _add(out, "tests/conftest.py", CONFTEST.encode())
        _add(out, f"tests/{test_name}", source.encode())
    return buf.getvalue()


# --- Sandbox execution ----------------------------------------------------------------
def run_in_sandbox(client, image: str, workspace: bytes, test_name: str, timeout_s: int) -> tuple[str, str]:
    container = client.containers.create(
        image, command=["python", "-m", "pytest", "-v", "-rA", "-p", "no:cacheprovider",
                        "--color=no", f"/work/tests/{test_name}"],
        working_dir="/work", user=f"{SANDBOX_UID}:{SANDBOX_UID}",
        environment={"PYTHONDONTWRITEBYTECODE": "1", "PYTHONUNBUFFERED": "1", "HOME": "/tmp"},
        network_mode="none", mem_limit=MEM, memswap_limit=MEM,
        nano_cpus=int(CPUS * 1e9), pids_limit=PIDS, cap_drop=["ALL"],
        security_opt=["no-new-privileges"], privileged=False, tmpfs={"/tmp": "size=64m"},
        labels={"evap.role": "sil-sandbox"}, detach=True)
    try:
        container.put_archive("/work", workspace)
        container.start()
        try:
            code = container.wait(timeout=timeout_s)["StatusCode"]
            verdict = {0: "PASS", 1: "FAIL"}.get(code, "ERROR")
            note = "" if code in (0, 1) else f"\n[evap] pytest exit code {code} -> ERROR"
        except Exception:  # requests timeout -> kill the test
            container.kill()
            verdict, note = "ERROR", f"\n[evap] TIMEOUT after {timeout_s}s — sandbox killed"
        logs = container.logs(stdout=True, stderr=True).decode(errors="replace")
        return verdict, logs + note
    finally:
        container.remove(force=True)


def process(client, payload: dict) -> None:
    run = payload["run"]
    rid = run["id"]
    log.info("run %s: %s@%s (%s)", rid, run["repo_url"], run["branch"], run["commit_sha"] or "HEAD")
    try:
        repo = mirror(run["repo_url"])
        sha = resolve_commit(repo, run["branch"], run["commit_sha"])
        if not run["commit_sha"]:
            api("POST", f"/api/runner/runs/{rid}/commit", {"commit_sha": sha})
        sut = git("archive", "--format=tar", sha, cwd=repo, binary=True)
        image = IMAGES.get(run["python_env"])
        if not image:
            raise RuntimeError(f"Unknown python environment {run['python_env']}")
    except Exception as exc:
        log.error("run %s: preparation failed: %s", rid, exc)
        api("POST", f"/api/runner/runs/{rid}/complete", {"error": f"Preparation failed: {exc}"[:4000]})
        return

    for ex in payload["executions"]:
        eid = ex["execution_id"]
        api("POST", f"/api/runner/executions/{eid}", {"status": "RUNNING"})
        header = (f"[evap] run={rid} commit={sha} test_case={ex['tc_id']} requirement={ex['requirement_code']} "
                  f"script_rev={ex['script_revision']} sha256={ex['sha256']}\n")
        t0 = time.monotonic()
        if hashlib.sha256(ex["source"].encode()).hexdigest() != ex["sha256"]:
            verdict, out = "ERROR", "[evap] script checksum mismatch — refusing to execute"
        else:
            name = "test_" + "".join(c if c.isalnum() else "_" for c in ex["tc_id"]).lower() + ".py"
            try:
                verdict, out = run_in_sandbox(client, image, build_workspace(sut, name, ex["source"]),
                                              name, int(run["timeout_s"]))
            except Exception as exc:
                verdict, out = "ERROR", f"[evap] sandbox error: {exc}"
        dur = round(time.monotonic() - t0, 3)
        log.info("run %s: %s -> %s (%.2fs)", rid, ex["tc_id"], verdict, dur)
        api("POST", f"/api/runner/executions/{eid}", {"status": verdict, "log": header + out, "duration_s": dur})
    res = api("POST", f"/api/runner/runs/{rid}/complete", {})
    log.info("run %s finished: %s, quality gate %s", rid, res["status"], res["quality_gate"])


def main() -> None:
    os.makedirs(CACHE, exist_ok=True)
    client = None
    while client is None:
        try:
            client = docker.from_env()
            client.ping()
        except DockerException as exc:
            log.warning("docker not reachable (%s); retrying", exc)
            client = None
            time.sleep(5)
    while True:
        try:
            log.info("recovered stale runs: %s", api("POST", "/api/runner/recover")["recovered"])
            break
        except (urllib.error.URLError, OSError) as exc:
            log.warning("EVAP API not reachable (%s); retrying", exc)
            time.sleep(3)
    while True:
        try:
            payload = api("POST", "/api/runner/claim")
            if payload.get("run"):
                process(client, payload)
                continue
        except (urllib.error.URLError, OSError) as exc:
            log.warning("API error: %s", exc)
        time.sleep(POLL_S)


if __name__ == "__main__":
    main()
